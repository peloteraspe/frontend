CREATE OR REPLACE FUNCTION public.set_featured_team(p_team_id BIGINT DEFAULT NULL)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
  v_user_id UUID := auth.uid();
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'AUTH_REQUIRED';
  END IF;

  IF p_team_id IS NOT NULL AND NOT EXISTS (
    SELECT 1
    FROM public.team_member member
    JOIN public.team team ON team.id = member.team_id
    WHERE member.team_id = p_team_id
      AND member.user_id = v_user_id
      AND member.status = 'active'
      AND team.is_active = true
      AND team.deleted_at IS NULL
  ) THEN
    RAISE EXCEPTION 'FEATURED_TEAM_MEMBERSHIP_REQUIRED';
  END IF;

  UPDATE public.profile
  SET featured_team_id = p_team_id
  WHERE "user" = v_user_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'PROFILE_NOT_FOUND';
  END IF;

  RETURN p_team_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.update_team_as_captain(
  p_team_id BIGINT,
  p_name TEXT,
  p_avatar_url TEXT DEFAULT NULL,
  p_instagram_username TEXT DEFAULT NULL,
  p_tiktok_username TEXT DEFAULT NULL
)
RETURNS public.team
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_team public.team%ROWTYPE;
  v_name TEXT := btrim(COALESCE(p_name, ''));
BEGIN
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'AUTH_REQUIRED'; END IF;
  IF char_length(v_name) NOT BETWEEN 2 AND 80 THEN
    RAISE EXCEPTION 'TEAM_NAME_INVALID';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.team_member member
    WHERE member.team_id = p_team_id
      AND member.user_id = v_user_id
      AND member.role = 'captain'
      AND member.status = 'active'
  ) THEN
    RAISE EXCEPTION 'CAPTAIN_REQUIRED';
  END IF;

  UPDATE public.team
  SET name = v_name,
      avatar_url = NULLIF(btrim(COALESCE(p_avatar_url, '')), ''),
      instagram_username = NULLIF(regexp_replace(btrim(COALESCE(p_instagram_username, '')), '^@+', ''), ''),
      tiktok_username = NULLIF(regexp_replace(btrim(COALESCE(p_tiktok_username, '')), '^@+', ''), '')
  WHERE id = p_team_id AND is_active = true AND deleted_at IS NULL
  RETURNING * INTO v_team;

  IF v_team.id IS NULL THEN RAISE EXCEPTION 'TEAM_NOT_FOUND'; END IF;
  RETURN v_team;
END;
$$;

CREATE OR REPLACE FUNCTION public.remove_team_member(
  p_team_id BIGINT,
  p_member_id BIGINT
)
RETURNS public.team_member
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_member public.team_member%ROWTYPE;
BEGIN
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'AUTH_REQUIRED'; END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.team_member captain
    WHERE captain.team_id = p_team_id AND captain.user_id = v_user_id
      AND captain.role = 'captain' AND captain.status = 'active'
  ) THEN RAISE EXCEPTION 'CAPTAIN_REQUIRED'; END IF;

  SELECT * INTO v_member FROM public.team_member
  WHERE id = p_member_id AND team_id = p_team_id FOR UPDATE;
  IF v_member.id IS NULL OR v_member.status <> 'active' THEN
    RAISE EXCEPTION 'ACTIVE_MEMBER_NOT_FOUND';
  END IF;
  IF v_member.role = 'captain' THEN RAISE EXCEPTION 'CANNOT_REMOVE_CAPTAIN'; END IF;

  UPDATE public.team_member
  SET status = 'removed', ended_at = now()
  WHERE id = p_member_id RETURNING * INTO v_member;

  UPDATE public.profile SET featured_team_id = NULL
  WHERE "user" = v_member.user_id AND featured_team_id = p_team_id;
  RETURN v_member;
END;
$$;

CREATE OR REPLACE FUNCTION public.transfer_team_captain(
  p_team_id BIGINT,
  p_new_captain_member_id BIGINT
)
RETURNS public.team_member
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_current public.team_member%ROWTYPE;
  v_next public.team_member%ROWTYPE;
BEGIN
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'AUTH_REQUIRED'; END IF;

  SELECT * INTO v_current FROM public.team_member
  WHERE team_id = p_team_id AND user_id = v_user_id
    AND role = 'captain' AND status = 'active' FOR UPDATE;
  IF v_current.id IS NULL THEN RAISE EXCEPTION 'CAPTAIN_REQUIRED'; END IF;

  SELECT * INTO v_next FROM public.team_member
  WHERE id = p_new_captain_member_id AND team_id = p_team_id
    AND status = 'active' FOR UPDATE;
  IF v_next.id IS NULL THEN RAISE EXCEPTION 'ACTIVE_MEMBER_NOT_FOUND'; END IF;
  IF v_next.id = v_current.id THEN RETURN v_current; END IF;

  UPDATE public.team_member SET role = 'player' WHERE id = v_current.id;
  UPDATE public.team_member SET role = 'captain' WHERE id = v_next.id RETURNING * INTO v_next;
  RETURN v_next;
END;
$$;

CREATE OR REPLACE FUNCTION public.leave_team(p_team_id BIGINT)
RETURNS public.team_member
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_member public.team_member%ROWTYPE;
BEGIN
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'AUTH_REQUIRED'; END IF;
  SELECT * INTO v_member FROM public.team_member
  WHERE team_id = p_team_id AND user_id = v_user_id AND status = 'active' FOR UPDATE;
  IF v_member.id IS NULL THEN RAISE EXCEPTION 'ACTIVE_MEMBER_NOT_FOUND'; END IF;

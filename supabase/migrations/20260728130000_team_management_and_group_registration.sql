  assistant_id BIGINT NOT NULL
    REFERENCES public.assistants(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  unit_price NUMERIC NOT NULL CHECK (unit_price >= 0),
  CONSTRAINT team_event_registration_member_user_unique UNIQUE (registration_id, user_id),
  CONSTRAINT team_event_registration_member_assistant_unique UNIQUE (assistant_id)

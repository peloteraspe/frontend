ALTER TABLE public.profile
  ADD COLUMN IF NOT EXISTS featured_team_id BIGINT
  REFERENCES public.team(id) ON UPDATE CASCADE ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS profile_featured_team_id_idx
  ON public.profile(featured_team_id)
  WHERE featured_team_id IS NOT NULL;

ALTER TABLE public.event
  ADD COLUMN IF NOT EXISTS allows_team_registration BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS team_registration_min_players SMALLINT,
  ADD COLUMN IF NOT EXISTS team_registration_max_players SMALLINT;

ALTER TABLE public.event
  DROP CONSTRAINT IF EXISTS event_team_registration_limits_check;

ALTER TABLE public.event
  ADD CONSTRAINT event_team_registration_limits_check CHECK (
    (team_registration_min_players IS NULL OR team_registration_min_players > 0)
    AND (team_registration_max_players IS NULL OR team_registration_max_players > 0)
    AND (
      team_registration_min_players IS NULL
      OR team_registration_max_players IS NULL
      OR team_registration_min_players <= team_registration_max_players
    )
  );

CREATE TABLE IF NOT EXISTS public.team_event_registration (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  event_id BIGINT NOT NULL REFERENCES public.event(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  team_id BIGINT NOT NULL REFERENCES public.team(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  registered_by_user_id UUID NOT NULL REFERENCES auth.users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  operation_number TEXT NOT NULL,
  unit_price NUMERIC NOT NULL CHECK (unit_price >= 0),
  participant_count INTEGER NOT NULL CHECK (participant_count > 0),
  total_amount NUMERIC NOT NULL CHECK (total_amount >= 0),
  state TEXT NOT NULL DEFAULT 'pending'
    CHECK (state IN ('pending', 'approved', 'rejected', 'cancelled')),
  reviewed_at TIMESTAMPTZ,
  reviewed_by_user_id UUID REFERENCES auth.users(id) ON UPDATE CASCADE ON DELETE SET NULL,
  reject_reason TEXT,
  CONSTRAINT team_event_registration_operation_number_check
    CHECK (operation_number ~ '^[0-9]{8}$')
);

CREATE UNIQUE INDEX IF NOT EXISTS team_event_registration_active_team_event_idx
  ON public.team_event_registration(event_id, team_id)
  WHERE state IN ('pending', 'approved');

CREATE INDEX IF NOT EXISTS team_event_registration_event_state_idx
  ON public.team_event_registration(event_id, state, created_at DESC);

CREATE INDEX IF NOT EXISTS team_event_registration_team_state_idx
  ON public.team_event_registration(team_id, state, created_at DESC);

ALTER TABLE public.assistants
  ADD COLUMN IF NOT EXISTS team_event_registration_id BIGINT
    REFERENCES public.team_event_registration(id) ON UPDATE CASCADE ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS team_id BIGINT
    REFERENCES public.team(id) ON UPDATE CASCADE ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS assistants_team_event_registration_idx
  ON public.assistants(team_event_registration_id)
  WHERE team_event_registration_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS assistants_team_event_idx
  ON public.assistants(team_id, event)
  WHERE team_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.team_event_registration_member (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  registration_id BIGINT NOT NULL
    REFERENCES public.team_event_registration(id) ON UPDATE CASCADE ON DELETE CASCADE,
  team_member_id BIGINT NOT NULL
